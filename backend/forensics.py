"""PDF structural forensics: traces that a document was edited after it was generated."""
import io
import re
from datetime import datetime

from pypdf import PdfReader

EDITOR_TOOLS = ["ilovepdf", "smallpdf", "sejda", "pdfescape", "pdf-xchange", "foxit phantom", "pdfelement",
                "acrobat pro", "nitro", "online pdf editor", "pdf editor", "canva", "photoshop"]


def _pdf_date(s):
    if not s:
        return None
    m = re.match(r"D:(\d{4})(\d{2})(\d{2})(\d{2})?(\d{2})?(\d{2})?", str(s))
    if not m:
        return None
    parts = [int(p) if p else 0 for p in m.groups()]
    try:
        return datetime(*parts)
    except ValueError:
        return None


def analyze(data: bytes, usual_producer: str | None = None) -> dict:
    flags = []
    if data[:4] != b"%PDF":
        return {"verdict": "not-applicable", "flags": [], "facts": {"note": "Not a PDF; structural forensics skipped"}}

    revisions = data.count(b"%%EOF")
    try:
        meta = PdfReader(io.BytesIO(data)).metadata or {}
    except Exception:  # noqa: BLE001
        meta = {}
    producer = str(meta.get("/Producer", "") or "")
    creator = str(meta.get("/Creator", "") or "")
    created, modified = _pdf_date(meta.get("/CreationDate")), _pdf_date(meta.get("/ModDate"))

    if revisions > 1:
        flags.append({"severity": "high", "title": f"Edited after creation ({revisions - 1} incremental revision{'s' if revisions > 2 else ''})",
                      "detail": "The file has extra save sections appended after the original. Original content may have been altered."})
    tool = next((t for t in EDITOR_TOOLS if t in (producer + " " + creator).lower()), None)
    if tool:
        flags.append({"severity": "high", "title": f"Saved by a PDF editing tool ({producer or creator})",
                      "detail": "Invoices are normally generated by accounting/ERP software, not edited in a PDF editor."})
    if usual_producer and producer and usual_producer.lower() not in producer.lower() and not tool:
        flags.append({"severity": "medium", "title": "Producer differs from seller's usual software",
                      "detail": f"Seller's past invoices come from '{usual_producer}', this one from '{producer}'."})
    if created and modified and (modified - created).total_seconds() > 60:
        delta = modified - created
        hours = delta.total_seconds() / 3600
        flags.append({"severity": "medium", "title": "Modified after it was created",
                      "detail": f"Modification timestamp is {hours:.1f} hours after creation."})
    if created and created > datetime.now():
        flags.append({"severity": "high", "title": "Creation date is in the future", "detail": str(created)})

    high = any(f["severity"] == "high" for f in flags)
    verdict = "tampered" if high else ("suspicious" if flags else "clean")
    return {"verdict": verdict, "flags": flags,
            "facts": {"revisions": revisions, "producer": producer or None, "creator": creator or None,
                      "created": created.isoformat() if created else None,
                      "modified": modified.isoformat() if modified else None, "usual_producer": usual_producer}}
